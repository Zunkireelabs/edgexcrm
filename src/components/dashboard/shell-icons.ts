/**
 * Where the same lucide name means two different things, the nav item (href) wins.
 * e.g. MessageSquare = Inbox on /inbox but SMS on /sms; FileText = a form on /forms
 * but a proposal on /proposals.
 */
export const SHELL_ICONS_BY_HREF: Record<string, Icon> = {
  "/inbox": Tray,
  "/sms": ChatText,
  "/forms": ClipboardText,
  "/classes": ChalkboardTeacher,
  "/knowledge-bases": Books,
  "/leave": CalendarDots,
  "/attendance": CalendarCheck,
  "/team": TreeStructure,
  "/pulse": Pulse,
  "/insights/dashboards": SquaresFour,
  "/time-tracking": Timer,
  "/approvals": Checks,
  "/tasks": ListChecks,
  "/projects": FolderSimple,
  "/resourcing": UsersThree,
  "/resourcing/utilization": Gauge,
  "/people": UserGear,
  "/contacts": AddressBook,
  "/pipeline": Kanban,
};

export function shellIcon(name: string | undefined, href?: string): Icon {
  if (href && SHELL_ICONS_BY_HREF[href]) return SHELL_ICONS_BY_HREF[href];
  return (name && SHELL_ICONS_BY_NAME[name]) || FileText;
}

